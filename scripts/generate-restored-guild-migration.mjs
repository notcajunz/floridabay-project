#!/usr/bin/env node
// Generates a forward-only MariaDB migration that rewrites Discord guild, role and
// channel IDs after guilds were restored from a backup, using the *-id-map.json
// files written by scripts/restore-network-guilds.mjs / restore-main-guild.mjs.
//
//   generate-restored-guild-migration.mjs [--profile=network|main] OUT.sql RESTORE_REF TITLE MAP.json [MAP.json ...]
//
// The network profile rewrites the satellite guilds (IAA, Departments, Gangs, DevOps, Businesses).
// The main profile moves the main-server rows written by migration 117 from the interim main guild
// onto the guild the main server was finally restored into.
//
// Scalar ID columns are rewritten through a join against discord_restore_id_map, which stays in
// the database as the audit trail of every old -> new ID. JSON configuration columns are rewritten
// ID by ID, quoted, so a value is only ever replaced when it is a complete Discord snowflake.
// Historical migrations are never edited, and Discord's backup tables keep their original IDs.
import { readFileSync, writeFileSync } from "node:fs";

const args = process.argv.slice(2);
const profile = (args.find((a) => a.startsWith("--profile=")) || "--profile=network").slice(10);
const [out, ref, title, ...mapFiles] = args.filter((a) => !a.startsWith("--profile="));
if (!out || !ref || !title || !mapFiles.length) {
  console.error("usage: generate-restored-guild-migration.mjs OUT.sql RESTORE_REF TITLE MAP.json ...");
  process.exit(2);
}

const maps = mapFiles.map((file) => JSON.parse(readFileSync(file, "utf8")));
const q = (value) => `'${String(value).replace(/'/g, "''")}'`;
for (const map of maps) {
  for (const id of [map.sourceGuildId, map.targetGuildId, ...Object.keys(map.roles), ...Object.values(map.roles), ...Object.keys(map.channels), ...Object.values(map.channels)]) {
    if (!/^\d{17,20}$/.test(id)) throw new Error(`not a snowflake: ${id}`);
  }
}

// JSON configuration columns that store IDs, each limited to the guild they belong to.
const JSON_TARGETS = [
  { table: "iaa_config", column: "config_value", where: null, guildIds: ["1558227271641210912"] },
  { table: "devops_config", column: "config_value", where: null, guildIds: ["1559599608479354992"] },
  { table: "bot_config", column: "value", where: "`key`='dept_application_main_log'", guildIds: ["1558235113295315004"] },
];

const lines = [];
const emit = (text = "") => lines.push(text);

emit(`-- ${title}`);
emit("-- Generated by scripts/generate-restored-guild-migration.mjs from the restore id maps.");
emit("-- Forward-only and safe to retry: every rewrite joins old IDs that no longer exist after the first run.");
emit("");
emit("CREATE TABLE IF NOT EXISTS discord_restore_id_map (");
emit("  old_id VARCHAR(32) NOT NULL,");
emit("  new_id VARCHAR(32) NOT NULL,");
emit("  kind VARCHAR(16) NOT NULL,");
emit("  restore_ref VARCHAR(64) NOT NULL,");
emit("  guild_old VARCHAR(32) NOT NULL,");
emit("  guild_new VARCHAR(32) NOT NULL,");
emit("  PRIMARY KEY (old_id, restore_ref),");
emit("  KEY discord_restore_id_map_new (new_id)");
emit(") ENGINE=InnoDB;");
emit("");

// Every guild's own map is a separate generation so the same ID can be remapped again later.
emit(`DELETE FROM discord_restore_id_map WHERE restore_ref=${q(ref)};`);
const rows = [];
for (const map of maps) {
  rows.push([map.sourceGuildId, map.targetGuildId, "guild", map.sourceGuildId, map.targetGuildId]);
  for (const [oldId, newId] of Object.entries(map.roles)) if (oldId !== map.sourceGuildId) rows.push([oldId, newId, "role", map.sourceGuildId, map.targetGuildId]);
  for (const [oldId, newId] of Object.entries(map.channels)) rows.push([oldId, newId, "channel", map.sourceGuildId, map.targetGuildId]);
}
for (let index = 0; index < rows.length; index += 150) {
  emit("INSERT IGNORE INTO discord_restore_id_map(old_id,new_id,kind,restore_ref,guild_old,guild_new) VALUES");
  emit(rows.slice(index, index + 150).map(([o, n, k, go, gn]) => `  (${q(o)},${q(n)},${q(k)},${q(ref)},${q(go)},${q(gn)})`).join(",\n") + ";");
}
emit("");

const R = `m.restore_ref=${q(ref)}`;
const guildOf = (table, column) => emit(`UPDATE ${table} t JOIN discord_restore_id_map m ON m.old_id=t.${column} AND m.kind='guild' AND ${R} SET t.${column}=m.new_id;`);
const idOf = (table, column, kinds) => emit(`UPDATE ${table} t JOIN discord_restore_id_map m ON m.old_id=t.${column} AND m.kind IN (${kinds.map(q).join(",")}) AND ${R} SET t.${column}=m.new_id;`);

if (profile === "main") {
  emit("-- Rows written by migration 117 for the interim main guild move to the restored main guild.");
  for (const [table, guild, ...ids] of [
    ["discord_role_bindings", "guild_id", ["role_id", "role"]],
    ["discord_role_sources", "guild_id", ["role_id", "role"]],
    ["network_sync_roles", "guild_id", ["role_id", "role"]],
    ["network_sync_anchors", "guild_id", ["below_role_id", "role"]],
    ["network_sync_guild_settings", "guild_id"],
    ["network_sync_guilds", "guild_id"],
    ["network_guilds", "guild_id"],
    ["protected_roles", "guild_id", ["role_id", "role"]],
    ["staff_roster_ranks", "discord_guild_id", ["discord_role_id", "role"]],
    ["staff_roster_jobs", "discord_guild_id", ["discord_role_id", "role"]],
    ["discord_channel_bindings", "guild_id", ["channel_id", "channel"]],
    ["audit_mirror_channels", "guild_id", ["channel_id", "channel"]],
    ["offices", "guild_id", ["channel_id", "channel"]],
    ["chain_of_command_config", "guild_id", ["channel_id", "channel"]],
    ["ticket_support_roles", "guild_id", ["role_id", "role"]],
  ]) {
    // Roles/channels first, while the guild column still identifies the interim rows.
    for (const [column, kind] of ids) idOf(table, column, [kind]);
    guildOf(table, guild);
  }
  emit("-- Ticket settings hold category and role IDs as plain values.");
  emit(`UPDATE ticket_settings t JOIN discord_restore_id_map m ON m.old_id=t.value AND m.kind IN ('role','channel') AND ${R} SET t.value=m.new_id;`);
  guildOf("ticket_settings", "guild_id");
  emit("-- Persistent boards are stored as JSON: replace complete quoted snowflakes only.");
  const map = maps[0];
  const pairs = [...Object.entries(map.roles).filter(([o]) => o !== map.sourceGuildId), ...Object.entries(map.channels)];
  for (const [oldId, newId] of pairs) {
    emit(`UPDATE bot_config SET value=REPLACE(value,${q(`"${oldId}"`)},${q(`"${newId}"`)}) WHERE value LIKE ${q(`%"${oldId}"%`)} AND \`key\` IN ('community_join_panel','live_notifications','protected_role_board','server_status_board','ticket_panel');`);
  }
  emit("-- Caches repopulate from Discord when the bots start.");
  emit(`DELETE FROM discord_guild_roles WHERE guild_id IN (${q(map.sourceGuildId)},${q(map.targetGuildId)});`);
  emit(`DELETE FROM discord_member_cache WHERE guild_id IN (${q(map.sourceGuildId)},${q(map.targetGuildId)});`);
  writeFileSync(out, `${lines.join("\n")}\n`);
  console.log(`${out}: ${rows.length} mappings, ${lines.length} lines`);
  process.exit(0);
}

const scalar = (table, column, kind) =>
  emit(`UPDATE ${table} t JOIN discord_restore_id_map m ON m.old_id=t.${column} AND ${R} AND m.kind IN (${kind.map(q).join(",")}) SET t.${column}=m.new_id;`);

emit("-- Cached role lists mirror Discord. Drop roles that were already gone from the backup, then move the rest.");
emit(`DELETE r FROM discord_guild_roles r JOIN discord_restore_id_map g ON g.old_id=r.guild_id AND g.kind='guild' AND g.restore_ref=${q(ref)}`);
emit(`  LEFT JOIN discord_restore_id_map m ON m.old_id=r.role_id AND m.restore_ref=${q(ref)} WHERE m.old_id IS NULL;`);
emit(`UPDATE discord_guild_roles r JOIN discord_restore_id_map g ON g.old_id=r.guild_id AND g.kind='guild' AND g.restore_ref=${q(ref)}`);
emit(`  JOIN discord_restore_id_map m ON m.old_id=r.role_id AND m.restore_ref=${q(ref)} SET r.guild_id=g.new_id, r.role_id=m.new_id;`);
emit("");

emit("-- Role-sourced groups, network synchronisation and protected roles.");
emit(`UPDATE discord_role_sources r JOIN discord_restore_id_map g ON g.old_id=r.guild_id AND g.kind='guild' AND g.restore_ref=${q(ref)}`);
emit(`  JOIN discord_restore_id_map m ON m.old_id=r.role_id AND m.restore_ref=${q(ref)} SET r.guild_id=g.new_id, r.role_id=m.new_id;`);
emit(`UPDATE network_sync_roles r JOIN discord_restore_id_map g ON g.old_id=r.guild_id AND g.kind='guild' AND g.restore_ref=${q(ref)}`);
emit(`  JOIN discord_restore_id_map m ON m.old_id=r.role_id AND m.restore_ref=${q(ref)} SET r.guild_id=g.new_id, r.role_id=m.new_id;`);
emit(`UPDATE protected_roles r JOIN discord_restore_id_map g ON g.old_id=r.guild_id AND g.kind='guild' AND g.restore_ref=${q(ref)}`);
emit(`  JOIN discord_restore_id_map m ON m.old_id=r.role_id AND m.restore_ref=${q(ref)} SET r.guild_id=g.new_id, r.role_id=m.new_id;`);
emit(`UPDATE network_sync_anchors a JOIN discord_restore_id_map m ON m.old_id=a.below_role_id AND ${R} SET a.below_role_id=m.new_id;`);
for (const table of ["network_sync_anchors", "network_sync_guild_settings", "network_guilds", "network_sync_guilds", "chain_of_command_config"]) {
  emit(`UPDATE ${table} t JOIN discord_restore_id_map m ON m.old_id=t.guild_id AND m.kind='guild' AND ${R} SET t.guild_id=m.new_id;`);
}
emit("");

emit("-- Agency and DevOps rank ladders.");
scalar("iaa_ranks", "role_id", ["role"]);
scalar("iaa_ranks", "tier_role_id", ["role"]);
scalar("devops_ranks", "role_id", ["role"]);
emit("");

emit("-- JSON configuration: replace complete quoted snowflakes only.");
for (const target of JSON_TARGETS) {
  const map = maps.find((m) => target.guildIds.includes(m.sourceGuildId));
  if (!map) continue;
  const pairs = [
    [map.sourceGuildId, map.targetGuildId],
    ...Object.entries(map.roles).filter(([o]) => o !== map.sourceGuildId),
    ...Object.entries(map.channels),
  ];
  for (const [oldId, newId] of pairs) {
    const filter = [`${target.column} LIKE ${q(`%"${oldId}"%`)}`, target.where].filter(Boolean).join(" AND ");
    emit(`UPDATE ${target.table} SET ${target.column}=REPLACE(${target.column},${q(`"${oldId}"`)},${q(`"${newId}"`)}) WHERE ${filter};`);
  }
}

writeFileSync(out, `${lines.join("\n")}\n`);
console.log(`${out}: ${rows.length} mappings, ${lines.length} lines`);
