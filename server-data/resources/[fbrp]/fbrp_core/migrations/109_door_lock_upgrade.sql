CREATE TABLE IF NOT EXISTS door_settings (
  id INT UNSIGNED AUTO_INCREMENT PRIMARY KEY,
  group_key VARCHAR(60) NOT NULL,
  model BIGINT NOT NULL,
  x DOUBLE NOT NULL,
  y DOUBLE NOT NULL,
  z DOUBLE NOT NULL,
  label VARCHAR(60) NULL,
  min_level TINYINT UNSIGNED NOT NULL DEFAULT 0,
  default_open BOOLEAN NOT NULL DEFAULT FALSE,
  auto_relock BOOLEAN NOT NULL DEFAULT TRUE,
  single BOOLEAN NOT NULL DEFAULT FALSE,
  updated_by VARCHAR(32) NULL,
  updated_at BIGINT NOT NULL,
  INDEX door_settings_group(group_key)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci;

